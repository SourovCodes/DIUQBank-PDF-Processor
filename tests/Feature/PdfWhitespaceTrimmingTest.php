beforeEach(function (): void {
    $this->workspace = sys_get_temp_dir().'/pdf-trim-test-'.bin2hex(random_bytes(6));
    mkdir($this->workspace);
});

afterEach(function (): void {
    if (is_dir($this->workspace)) {
        array_map('unlink', glob($this->workspace.'/*') ?: []);
        rmdir($this->workspace);
    }
});

function trimTestGhostscriptIsInstalled(): bool
{
    return Process::run(['gs', '--version'])->successful();
}

/**
 * A page holding a single black block, standing in for a photo dropped onto a
 * page with wide margins. Dimensions are in millimetres.
 *
 * @param  array{0: float, 1: float, 2: float, 3: float}|null  $block  x, y, width, height
 */
function makePdfWithBlock(string $path, float $pageWidth, float $pageHeight, ?array $block): string
{
    $pdf = new Fpdi;
    $pdf->SetMargins(0, 0, 0);
    $pdf->SetAutoPageBreak(false);
    $pdf->AddPage('P', [$pageWidth, $pageHeight]);

    if ($block !== null) {
        $pdf->SetFillColor(0, 0, 0);
        $pdf->Rect($block[0], $block[1], $block[2], $block[3], 'F');
    }

    $pdf->Output('F', $path);

    return $path;
}

/**
 * @param  array<int, array{0: int, 1: int}>  $darkPixels  x, y
 */
function makeBitmap(int $width, int $height, array $darkPixels): string
{
    $pixels = str_repeat("\xFF", $width * $height);

    foreach ($darkPixels as [$x, $y]) {
        $pixels[$y * $width + $x] = "\x00";
    }

    return "P5\n# Image generated by a test\n{$width} {$height}\n255\n".$pixels;
}

/**
 * @return array{0: float, 1: float}
 */
function pageSizeInPoints(string $path, int $page = 1): array
{
    [$width, $height] = (new PdfReader(new PdfParser(StreamReader::createByFile($path))))
        ->getPage($page)
        ->getWidthAndHeight();

    return [(float) $width, (float) $height];
}

test('a bitmap is cropped to its content plus padding', function (): void {
    config()->set('pdf.trim.render_resolution', 72);
    config()->set('pdf.trim.padding_points', 2.0);
    config()->set('pdf.trim.min_content_pixels', 1);

    $pixels = [];

    for ($x = 20; $x < 60; $x++) {
        for ($y = 30; $y < 50; $y++) {
            $pixels[] = [$x, $y];
        }
    }

    $crop = (new PdfWhitespaceDetector)->cropForBitmap(makeBitmap(100, 100, $pixels));

    expect($crop)->toBeInstanceOf(PageRegion::class)
        ->and($crop->left)->toEqualWithDelta(0.18, 0.0001)
        ->and($crop->top)->toEqualWithDelta(0.28, 0.0001)
        ->and($crop->right)->toEqualWithDelta(0.62, 0.0001)
        ->and($crop->bottom)->toEqualWithDelta(0.52, 0.0001);
});

test('a lone speck does not hold a margin open', function (): void {
    config()->set('pdf.trim.padding_points', 0.0);
    config()->set('pdf.trim.min_content_pixels', 2);

    $pixels = [[2, 2]];

    for ($x = 40; $x < 60; $x++) {
        for ($y = 40; $y < 60; $y++) {
            $pixels[] = [$x, $y];
        }
    }

    $crop = (new PdfWhitespaceDetector)->cropForBitmap(makeBitmap(100, 100, $pixels));

    expect($crop->left)->toEqualWithDelta(0.40, 0.0001)
        ->and($crop->top)->toEqualWithDelta(0.40, 0.0001);
});

test('blank and edge to edge bitmaps are left uncropped', function (): void {
    $detector = new PdfWhitespaceDetector;
    $fullPage = [];

    for ($x = 0; $x < 50; $x++) {
        for ($y = 0; $y < 50; $y++) {
            $fullPage[] = [$x, $y];
        }
    }

    expect($detector->cropForBitmap(makeBitmap(50, 50, [])))->toBeNull()
        ->and($detector->cropForBitmap(makeBitmap(50, 50, $fullPage)))->toBeNull()
        ->and($detector->cropForBitmap('not a bitmap'))->toBeNull();
});

test('a ghostscript failure leaves the document uncropped', function (): void {
    $binary = $this->workspace.'/gs';
    file_put_contents($binary, "#!/bin/sh\necho 'boom' >&2\nexit 1\n");
    chmod($binary, 0755);
    config()->set('pdf.ghostscript.binary', $binary);

    $input = makePdfWithBlock($this->workspace.'/in.pdf', 210.0, 297.0, [50.0, 50.0, 100.0, 100.0]);

    expect((new PdfWhitespaceDetector)->cropsFor($input))->toBe([]);
});

test('ghostscript renders find the margins around page content', function (): void {
    config()->set('pdf.trim.padding_points', 0.0);

    $input = makePdfWithBlock($this->workspace.'/in.pdf', 210.0, 297.0, [42.0, 59.4, 84.0, 118.8]);

    $crops = (new PdfWhitespaceDetector)->cropsFor($input);

    // One rendered pixel at 36 DPI is about 0.7mm, or 0.003 of an A4 width.
    expect($crops)->toHaveKey(1)
        ->and($crops[1]->left)->toEqualWithDelta(0.2, 0.01)
        ->and($crops[1]->top)->toEqualWithDelta(0.2, 0.01)
        ->and($crops[1]->right)->toEqualWithDelta(0.6, 0.01)
        ->and($crops[1]->bottom)->toEqualWithDelta(0.6, 0.01);
})->skip(fn (): bool => ! trimTestGhostscriptIsInstalled(), 'Ghostscript is not installed.');

test('compression trims white margins only when asked to', function (): void {
    $input = makePdfWithBlock($this->workspace.'/in.pdf', 210.0, 297.0, [50.0, 50.0, 100.0, 150.0]);
    $trimmed = $this->workspace.'/trimmed.pdf';
    $untouched = $this->workspace.'/untouched.pdf';

    app(PdfCompressor::class)->compress($input, $trimmed, new PageLayout(trimWhitespace: true));
    app(PdfCompressor::class)->compress($input, $untouched);

    $padding = 2 * (float) config('pdf.trim.padding_points');
    [$width, $height] = pageSizeInPoints($trimmed);

    expect($width)->toEqualWithDelta(100 / 25.4 * 72 + $padding, 3.0)
        ->and($height)->toEqualWithDelta(150 / 25.4 * 72 + $padding, 3.0)
        ->and(pageSizeInPoints($untouched)[0])->toEqualWithDelta(595.3, 0.5);
})->skip(fn (): bool => ! trimTestGhostscriptIsInstalled(), 'Ghostscript is not installed.');

test('the credit header spans the trimmed page width', function (): void {
    $input = makePdfWithBlock($this->workspace.'/in.pdf', 210.0, 297.0, [50.0, 50.0, 100.0, 150.0]);
    $output = $this->workspace.'/out.pdf';

    app(PdfCompressor::class)->compressWithCreditAndWatermark($input, $output, 'Uploaded by Sourov', 'DIUQBank.com', new PageLayout(trimWhitespace: true));

    $padding = 2 * (float) config('pdf.trim.padding_points');
    $expectedWidth = 100 / 25.4 * 72 + $padding;
    [$width, $height] = pageSizeInPoints($output);

    // The header is 8mm on a 210mm page, scaled to the narrower page and clamped at 4mm.
    $headerHeight = max(4.0, 8 / 210 * ($expectedWidth / 72 * 25.4)) / 25.4 * 72;

    expect($width)->toEqualWithDelta($expectedWidth, 3.0)
        ->and($height)->toEqualWithDelta(150 / 25.4 * 72 + $padding + $headerHeight, 3.0)
        ->and((new PdfPageGeometry)->narrowestPageWidthInPoints($output))->toEqualWithDelta($expectedWidth, 3.0);
})->skip(fn (): bool => ! trimTestGhostscriptIsInstalled(), 'Ghostscript is not installed.');

/**
 * @param  array<int, array{0: float, 1: float}>  $sizes  width and height of each page, in millimetres
 */
function makePdfWithPageSizes(string $path, array $sizes): string
{
    $pdf = new Fpdi;
    $pdf->SetMargins(0, 0, 0);
    $pdf->SetAutoPageBreak(false);

    foreach ($sizes as [$width, $height]) {
        $pdf->AddPage($width > $height ? 'L' : 'P', [$width, $height]);
        $pdf->SetFont('Arial', '', 6);
        $pdf->Cell(0, 5, 'page');
    }

    $pdf->Output('F', $path);

    return $path;
}

test('page layout scales a page to the uniform width and keeps its aspect ratio', function (): void {
    expect((new PageLayout(pageWidthMm: 210.0))->scaledSize(100.0, 50.0))->toBe([210.0, 105.0])
        ->and((new PageLayout)->scaledSize(100.0, 50.0))->toBe([100.0, 50.0]);
});

test('page layout reads the uniform width from config', function (): void {
    config()->set('pdf.layout.page_width_mm', 180);
    expect(PageLayout::fromConfig(true, true)->pageWidthMm)->toBe(180.0);

    config()->set('pdf.layout.page_width_mm', 0);
    expect(PageLayout::fromConfig(true, true)->pageWidthMm)->toBeNull();
});

test('a document already at the uniform width goes straight to ghostscript', function (): void {
    $binary = $this->workspace.'/gs';
    file_put_contents($binary, <<<SHELL
        #!/bin/sh
        for arg in "\$@"; do
            case "\$arg" in
                --version) echo "10.02.1"; exit 0 ;;
                -sOutputFile=*) OUT="\${arg#-sOutputFile=}" ;;
            esac
        done
        echo "\$@" >> "{$this->workspace}/invocations.log"
        printf '%%PDF-1.7 stub' > "\$OUT"
        SHELL);
    chmod($binary, 0755);
    config()->set('pdf.ghostscript.binary', $binary);

    $input = makePdfWithPageSizes($this->workspace.'/a4.pdf', [[210.0, 297.0], [210.0, 297.0]]);

    app(PdfCompressor::class)->compress($input, $this->workspace.'/out.pdf', new PageLayout(pageWidthMm: 210.0, removeScannerCredits: true));

    $invocations = array_values(array_filter(explode("\n", trim((string) file_get_contents($this->workspace.'/invocations.log')))));

    expect($invocations)->toHaveCount(1)
        ->and($invocations[0])->toEndWith($input);
});

test('pages of different sizes are scaled to the same width', function (): void {
    $input = makePdfWithPageSizes($this->workspace.'/mixed.pdf', [[210.0, 297.0], [100.0, 50.0], [74.0, 105.0]]);
    $output = $this->workspace.'/out.pdf';

    app(PdfCompressor::class)->compress($input, $output, new PageLayout(pageWidthMm: 210.0));

    $points = fn (float $millimetres): float => $millimetres / 25.4 * 72;

    expect(pageSizeInPoints($output, 1))->sequence(
        fn ($width) => $width->toEqualWithDelta($points(210.0), 0.5),
        fn ($height) => $height->toEqualWithDelta($points(297.0), 0.5),
    )->and(pageSizeInPoints($output, 2))->sequence(
        fn ($width) => $width->toEqualWithDelta($points(210.0), 0.5),
        fn ($height) => $height->toEqualWithDelta($points(105.0), 0.5),
    )->and(pageSizeInPoints($output, 3))->sequence(
        fn ($width) => $width->toEqualWithDelta($points(210.0), 0.5),
        fn ($height) => $height->toEqualWithDelta($points(105.0 * 210.0 / 74.0), 0.5),
    );
})->skip(fn (): bool => ! trimTestGhostscriptIsInstalled(), 'Ghostscript is not installed.');

test('trimmed pages are scaled up to the uniform width under the credit header', function (): void {
    $input = makePdfWithBlock($this->workspace.'/in.pdf', 210.0, 297.0, [50.0, 50.0, 100.0, 150.0]);
    $output = $this->workspace.'/out.pdf';

    app(PdfCompressor::class)->compressWithCreditAndWatermark($input, $output, 'Uploaded by Sourov', 'DIUQBank.com', new PageLayout(trimWhitespace: true, pageWidthMm: 210.0));

    $padding = 2 * (float) config('pdf.trim.padding_points');
    $croppedWidth = 100 / 25.4 * 72 + $padding;
    $croppedHeight = 150 / 25.4 * 72 + $padding;
    $a4Width = 210 / 25.4 * 72;
    $headerHeight = 8 / 25.4 * 72;
    [$width, $height] = pageSizeInPoints($output);

    expect($width)->toEqualWithDelta($a4Width, 0.5)
        ->and($height)->toEqualWithDelta($croppedHeight * $a4Width / $croppedWidth + $headerHeight, 6.0);
})->skip(fn (): bool => ! trimTestGhostscriptIsInstalled(), 'Ghostscript is not installed.');
